sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'pytorch')))
from model import Gesture1DCNN

# --- Configuration for the Gesture CNN ---
IN_CHANNELS = 6
IN_LENGTH = 128
NUM_CLASSES = 7

INPUT_DATA_SIZE = IN_CHANNELS * IN_LENGTH  # 6 * 128 = 768 floats
OUTPUT_DATA_SIZE = NUM_CLASSES             # 7 floats (logits)

# PYNQ 3.x can load an .xsa directly.
OVERLAY_PATH = "/home/ubuntu/pynq/overlays/cg4002_final_project/gesture_cnn.xsa" # TODO: Update with your actual path

def get_dma_instance(ol):
    if hasattr(ol, "axi_dma_0"):
        return ol.axi_dma_0

    dma_names = [
        name for name, desc in ol.ip_dict.items()
        if "axi_dma" in desc.get("type", "").lower() or "axi_dma" in name.lower()
    ]
    if dma_names:
        print(f"Using detected DMA instance: {dma_names[0]}")
        return getattr(ol, dma_names[0])
    raise RuntimeError("No AXI DMA instance found in overlay.ip_dict")

def software_reference(input_tensor):
    """
    Runs the PyTorch model with the same input to get the expected "golden" output.
    """
    # This assumes the script is run from the `pynq` directory
    model_path = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'pytorch', 'saved_checkpoints', 'gesture_1dcnn_best.pth'))
    if not os.path.exists(model_path):
        raise FileNotFoundError(f"Model checkpoint not found at {model_path}. Please run train_baseline.py first.")

    model = Gesture1DCNN(in_channels=IN_CHANNELS, num_classes=NUM_CLASSES)
    model.load_state_dict(torch.load(model_path, map_location='cpu'))
    model.eval()
    
    with torch.no_grad():
        output_tensor = model(input_tensor)
        
    return output_tensor.numpy().flatten()


def main():
    print(f"Loading overlay: {OVERLAY_PATH}")
    overlay = Overlay(OVERLAY_PATH)
    print("Overlay loaded")
    
    print("Discovered IP blocks:", list(overlay.ip_dict.keys()))
    dma = get_dma_instance(overlay)

    # Load the golden input vector generated by export_weights.py
    # This ensures we test the hardware with the exact same data as the HLS C-simulation.
    golden_input_path = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'vitis', 'hls_export', 'golden_input.dat'))
    if not os.path.exists(golden_input_path):
        raise FileNotFoundError(f"Golden input not found at {golden_input_path}. Please run export_weights.py first.")
    
    input_data = np.loadtxt(golden_input_path, dtype=np.float32)

    if input_data.size != INPUT_DATA_SIZE:
        raise RuntimeError(f"Input size mismatch: loaded {input_data.size} floats, expected {INPUT_DATA_SIZE}")

    # Reshape for the PyTorch model (Batch, Channels, Length)
    input_tensor = torch.from_numpy(input_data).reshape(1, IN_CHANNELS, IN_LENGTH)
    expected_output = software_reference(input_tensor)

